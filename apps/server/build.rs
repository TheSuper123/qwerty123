use std::{env, fs, path::PathBuf};
fn main() {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap()).join("../..");
    println!("cargo:rerun-if-env-changed=MOST_LICENSES_FILE");
    let contents = if let Some(path) = env::var_os("MOST_LICENSES_FILE") {
        let path = PathBuf::from(path);
        println!("cargo:rerun-if-changed={}", path.display());
        fs::read_to_string(path).expect("Collect dependency notices before a distribution build")
    } else {
        assert_ne!(
            env::var("PROFILE").unwrap(),
            "release",
            "Release builds require MOST_LICENSES_FILE generated by scripts/collect_licenses.py"
        );
        println!("cargo:rerun-if-changed={}", root.join("LICENSE").display());
        println!(
            "cargo:rerun-if-changed={}",
            root.join("THIRD_PARTY_NOTICES.md").display()
        );
        format!(
            "Development build; full distribution notices are embedded by the release workflow.\n\n{}\n\n{}",
            fs::read_to_string(root.join("LICENSE")).unwrap(),
            fs::read_to_string(root.join("THIRD_PARTY_NOTICES.md")).unwrap()
        )
    };
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("licenses.txt"),
        contents,
    )
    .unwrap();
}
